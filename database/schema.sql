-- Healthcare Management App: readable database schema (PostgreSQL)
-- Same tables and columns that Django creates with "python manage.py migrate".
-- For the real project use migrate. This file is for reading, diagrams and the viva.

-- 1. Users (Admin / Doctor / Staff) ------------------------------------------
CREATE TABLE accounts_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(150) NOT NULL UNIQUE,
    password      VARCHAR(128) NOT NULL,              -- stored as a hash, never plain text
    email         VARCHAR(254) NOT NULL,
    first_name    VARCHAR(150) NOT NULL DEFAULT '',
    last_name     VARCHAR(150) NOT NULL DEFAULT '',
    role          VARCHAR(10)  NOT NULL DEFAULT 'staff'
                  CHECK (role IN ('admin', 'doctor', 'staff')),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    is_staff      BOOLEAN NOT NULL DEFAULT FALSE,     -- can open /admin/
    is_superuser  BOOLEAN NOT NULL DEFAULT FALSE,
    last_login    TIMESTAMPTZ,
    date_joined   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Login tokens (Django REST Framework authtoken) --------------------------
CREATE TABLE authtoken_token (
    key      VARCHAR(40) PRIMARY KEY,
    created  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_id  BIGINT NOT NULL UNIQUE REFERENCES accounts_user(id) ON DELETE CASCADE
);

-- 3. Patients ----------------------------------------------------------------
CREATE TABLE patients_patient (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name          VARCHAR(100) NOT NULL,
    last_name           VARCHAR(100) NOT NULL,
    date_of_birth       DATE NOT NULL,
    gender              VARCHAR(10) NOT NULL CHECK (gender IN ('male', 'female', 'other')),
    phone               VARCHAR(20) NOT NULL DEFAULT '',
    email               VARCHAR(254) NOT NULL DEFAULT '',
    address             TEXT NOT NULL DEFAULT '',
    assigned_doctor_id  BIGINT REFERENCES accounts_user(id) ON DELETE SET NULL,
    created_by_id       BIGINT REFERENCES accounts_user(id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_patient_assigned_doctor ON patients_patient(assigned_doctor_id);
CREATE INDEX idx_patient_created_by      ON patients_patient(created_by_id);

-- 4. Medical documents (one patient has many documents) ----------------------
CREATE TABLE documents_document (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      BIGINT NOT NULL REFERENCES patients_patient(id) ON DELETE CASCADE,
    name            VARCHAR(255) NOT NULL,
    document_type   VARCHAR(50)  NOT NULL DEFAULT '',   -- filled in by the AI
    file            VARCHAR(100) NOT NULL,              -- path of the PDF on disk
    uploaded_by_id  BIGINT REFERENCES accounts_user(id) ON DELETE SET NULL,
    uploaded_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status          VARCHAR(20) NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'processing', 'completed', 'failed')),
    extracted_text  TEXT NOT NULL DEFAULT '',           -- text read from the PDF
    ai_result       JSONB,                              -- validated AI answer, see below
    error_message   VARCHAR(255) NOT NULL DEFAULT ''
);
CREATE INDEX idx_document_patient ON documents_document(patient_id);
CREATE INDEX idx_document_status  ON documents_document(status);

-- ai_result looks like:
-- {"document_type": "lab report",
--  "summary": "...",
--  "test_results": [{"name": "...", "value": "...", "unit": "...", "date": "..."}]}

-- 5. Audit log (ids only, no patient details) --------------------------------
CREATE TABLE audit_auditlog (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT REFERENCES accounts_user(id) ON DELETE SET NULL,
    action       VARCHAR(50) NOT NULL,     -- login, patient_created, patient_updated,
                                           -- patient_deleted, document_uploaded
    object_type  VARCHAR(50) NOT NULL,     -- user, patient, document
    object_id    INTEGER,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_audit_user ON audit_auditlog(user_id);
